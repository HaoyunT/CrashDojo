"""Finite-sample consistency bounds implied by the paper's reported summaries.

This script does not reconstruct seeds or run experiments. It assumes each
table cell is the rounded mean and sample standard deviation of three seed
summaries, as stated in the paper. Bounds concern those three summaries only;
they are neither confidence intervals nor scene-level paired estimates.
"""
import argparse
import json
import math
import random
import re
import statistics
import unittest
from decimal import Decimal, ROUND_FLOOR, getcontext
from pathlib import Path

getcontext().prec = 60
D = Decimal
METRICS = ("CR", "MS", "RM_tgt", "Adv_ADE", "Adv_FDE")
PLANNERS = ("IDM", "Diffusion Planner")


def half_rounding_unit(value):
    """Half the last displayed unit, retaining trailing decimal places."""
    return D(5) * D(10) ** (D(value).as_tuple().exponent - 1)


def lower_bound(full, variant, higher_is_better, n=3):
    if n < 2:
        raise ValueError("A sample standard deviation requires n >= 2")
    fm, fs = map(D, full)
    vm, vs = map(D, variant)
    if min(fs, vs) < 0:
        raise ValueError("Standard deviations cannot be negative")
    delta = fm - vm if higher_is_better else vm - fm
    mean_radius = half_rounding_unit(full[0]) + half_rounding_unit(variant[0])
    sd_sum_upper = fs + vs + half_rounding_unit(full[1]) + half_rounding_unit(variant[1])
    factor = D(n - 1) / D(n).sqrt()
    bound = delta - mean_radius - factor * sd_sum_upper - D("1e-40")
    return {"mean_difference_displayed": str(delta),
            "lower_bound": str(bound), "positive": bound > 0}


def parse_table(path):
    text = Path(path).read_text()
    if "three seeds" not in text or "sample standard deviation" not in text:
        raise ValueError("Table must declare three seeds and sample SD")
    data = {p: {} for p in PLANNERS}
    planner = None
    for line in text.splitlines():
        for p in PLANNERS:
            if r"\textit{" + p + "}" in line:
                planner = p
        if planner is None or "&" not in line:
            continue
        cells = line.split("&")
        match = re.search(r"A([0-4])\b", cells[0])
        if not match:
            continue
        variant = "A" + match.group(1)
        if len(cells) != 6:
            raise ValueError("Unexpected metric columns")
        parsed = {}
        for metric, cell in zip(METRICS, cells[1:]):
            values = re.findall(r"\d+(?:\.\d+)?", cell)
            if len(values) == 2:
                parsed[metric] = values
            elif not values and "--" in cell:
                parsed[metric] = None
            else:
                raise ValueError("Unrecognized table cell: " + cell)
        # The table source typesets the tabular twice (width measurement + output),
        # so identical repeated rows are expected; conflicting repeats are an error.
        if variant in data[planner]:
            if data[planner][variant] != parsed:
                raise ValueError("Conflicting duplicate row for " + planner + " " + variant)
            continue
        data[planner][variant] = parsed
    for p in PLANNERS:
        if set(data[p]) != {"A0", "A1", "A2", "A3", "A4"}:
            raise ValueError("Missing variants for " + p)
    return data


def analyze(data):
    rows = []
    for planner in PLANNERS:
        full = data[planner]["A0"]
        for variant in ("A1", "A2", "A3", "A4"):
            row = {"planner": planner, "variant": variant, "bounds": {}}
            for metric in METRICS:
                other = data[planner][variant][metric]
                row["bounds"][metric] = (None if other is None else
                    lower_bound(full[metric], other, metric in ("CR", "MS")))
            rows.append(row)
    return {"n_seeds": 3, "source": "Table 4 rounded mean and sample SD",
            "interpretation": "Bounds on the finite reported seeds; not confidence intervals",
            "rounding": "Half a last-displayed unit for means and SDs; output rounded downward",
            "rows": rows}


def latex_table(result):
    lines = [r"% Generated by analysis/seed_summary_bounds.py from Table 4.",
             r"\begin{table}[t]", r"\centering",
             r"\caption{\textbf{Bounds implied by the three-seed summaries.} "
             r"Lower bound on Full's difference from each variant over the reported seeds, "
             r"including display rounding (orientation as in the text). Bold positive "
             r"entries hold on every seed. -- denotes an unreported input.}",
             r"\label{tab:seed_bounds}",
             r"\begingroup\footnotesize\setlength{\tabcolsep}{3pt}\renewcommand{\arraystretch}{1.12}",
             r"\begin{tabular*}{\columnwidth}{@{\extracolsep{\fill}}lrrrrr@{}}",
             r"\toprule",
             r"Variant & CR (pp) & MS (m/s) & $\mathrm{RM}_{\rm tgt}$ & Adv.ADE (m) & Adv.FDE (m)\\"]
    previous = None
    for row in result["rows"]:
        if row["planner"] != previous:
            lines += [r"\midrule", r"\multicolumn{6}{@{}l}{\textit{" + row["planner"] + r"}}\\"]
            previous = row["planner"]
        cells = [row["variant"]]
        for metric in METRICS:
            item = row["bounds"][metric]
            if item is None:
                cells.append("--")
                continue
            quantum = D("0.0001") if metric == "RM_tgt" else D("0.01")
            value = D(item["lower_bound"]).quantize(quantum, rounding=ROUND_FLOOR)
            label = format(value, "f")
            cells.append(r"\textbf{" + label + "}" if value > 0 else label)
        lines.append(" & ".join(cells) + r"\\")
    lines += [r"\bottomrule", r"\end{tabular*}\endgroup", r"\end{table}", ""]
    return "\n".join(lines)


class BoundTests(unittest.TestCase):
    def test_sharp_sample_envelope(self):
        for n in range(2, 10):
            xs = [float(n - 1)] + [-1.0] * (n - 1)
            radius = (n - 1) / math.sqrt(n) * statistics.stdev(xs)
            self.assertAlmostEqual(max(xs) - statistics.mean(xs), radius)

    def test_rounded_bounds_cover_actual_differences(self):
        rng = random.Random(41027)
        for n in range(2, 9):
            for _ in range(300):
                full = [rng.uniform(-20, 20) for _ in range(n)]
                other = [rng.uniform(-20, 20) for _ in range(n)]
                fs = [format(statistics.mean(full), ".2f"), format(statistics.stdev(full), ".2f")]
                os = [format(statistics.mean(other), ".2f"), format(statistics.stdev(other), ".2f")]
                for direction in (True, False):
                    bound = float(lower_bound(fs, os, direction, n)["lower_bound"])
                    differences = [a - b if direction else b - a for a in full for b in other]
                    self.assertLessEqual(bound, min(differences) + 1e-10)

    def test_rounding_and_missing_advantage(self):
        self.assertEqual(half_rounding_unit("1.0"), D("0.05"))
        self.assertEqual(half_rounding_unit("0.0045"), D("0.00005"))
        self.assertFalse(lower_bound(["14.7", "2.9"], ["14.0", "3.6"], True)["positive"])
        self.assertTrue(lower_bound(["23.0", "1.0"], ["17.3", "2.1"], True)["positive"])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--table", type=Path, default=Path(__file__).resolve().parents[1] / "figures/tab_component_ablation.tex")
    parser.add_argument("--json", type=Path)
    parser.add_argument("--latex", type=Path)
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args()
    if args.self_test:
        suite = unittest.defaultTestLoader.loadTestsFromTestCase(BoundTests)
        if not unittest.TextTestRunner(verbosity=2).run(suite).wasSuccessful():
            raise SystemExit(1)
    result = analyze(parse_table(args.table))
    payload = json.dumps(result, indent=2) + "\n"
    if args.json:
        args.json.write_text(payload)
    if args.latex:
        args.latex.write_text(latex_table(result))
    if not args.json and not args.latex:
        print(payload, end="")


if __name__ == "__main__":
    main()
